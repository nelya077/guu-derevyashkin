"""
Задача 04-09. Каждое слово с заглавной

Прочитайте предложение и выведите его так, чтобы каждое слово начиналось
с заглавной буквы: «привет мир» → «Привет Мир».

Методом title() не пользоваться — разберите строку на слова, замените
первую букву каждого (capitalize) и соберите обратно через join.

Пример
------
Ввод:
привет большой мир
Вывод:
Привет Большой Мир
"""

# TODO: split → capitalize каждого слова → join
n = str(input())
new_n = n.split()
result = [n.capitalize() for n in new_n]
print(" ".join(result))

