"""
Задача 06-15. Средний балл

Прочитайте целое число n, затем n строк «имя предмет оценка» (имя и предмет —
одно слово, оценка — целое число). Для каждого студента выведите средний
балл по его предметам (round 2): строку «имя среднее». Студенты — в порядке
первого появления.

Пример
------
Ввод:
3
анна матем 5
борис физика 4
анна физика 3
Вывод:
анна 4.0
борис 4.0
"""

# TODO: словарь «имя → список оценок», затем средние
n = int(input())
name_subject = {}
for _ in range(n):
    name = input().split()
    name_subject.setdefault(name[0], []).append(int(name[2]))

for student, marks in name_subject.items():
    print(student, round(sum(marks) / len(marks), 2))
