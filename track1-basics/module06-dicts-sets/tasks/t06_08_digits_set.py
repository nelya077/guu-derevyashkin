"""
Задача 06-08. Какие цифры есть в строке

Прочитайте строку и выведите все различные цифры, которые в ней
встречаются, — по возрастанию, через пробел. Если цифр нет, ничего
не выводите.

Пример
------
Ввод:
a1b23c1
Вывод:
1 2 3
"""

# TODO: соберите множество цифр и выведите его по возрастанию
text = input()
n = set()
for i in text:
    if i.isdigit():
        n.add(i)
if n:
    print(*sorted(n))