"""
Задача 06-05. Телефонная книга

Прочитайте целое число n, затем n строк вида «имя номер» (имя — одно слово,
номер — строка без пробелов), затем ещё одну строку — имя для поиска.
Выведите номер этого абонента или «не найдено».

Пример
------
Ввод:
2
анна 111-22-33
борис 555-66-77
анна
Вывод:
111-22-33
"""

# TODO: соберите словарь из n строк и выполните поиск
n = int(input())
book = {}
for _ in range(n):
    name, number = input().split()
    book[name] = number

query = input()
if query in book:
    print(book[query])
else:
    print("не найдено")