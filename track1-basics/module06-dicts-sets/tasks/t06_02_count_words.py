"""
Задача 06-02. Частоты слов

Прочитайте предложение и посчитайте, сколько раз встречается каждое слово.
Выведите «слово количество» построчно — в порядке первого появления слова
в предложении.

Пример
------
Ввод:
мама мыла раму мама
Вывод:
мама 2
мыла 1
раму 1
"""

# TODO: посчитайте частоты слов словарём и выведите их

text = input().split()
counts = {}
for w in text:
    if w in counts:
        counts[w] += 1
    else:
        counts[w] = 0
for k, v in counts.items():
    print(k, v)