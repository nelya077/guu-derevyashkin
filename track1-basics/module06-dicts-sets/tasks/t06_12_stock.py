"""
Задача 06-12. Склад

Прочитайте целое число n, затем n строк «товар количество» — начальные
остатки склада. Затем целое число m и m строк «товар дельта» — операции
прихода/расхода (дельта может быть отрицательной). Товары в операциях
заведомо есть на складе.

Выведите итоговые остатки «товар: количество» построчно в порядке
первого появления товара в начальных остатках.

Пример
------
Ввод:
2
сахар 10
мука 5
2
сахар -3
мука 7
Вывод:
сахар: 7
мука: 12
"""

# TODO: соберите словарь остатков и примените операции
n = int(input())
warehouse = {}
for _ in range(n):
    name, qty= input().split()
    qty = int(qty)
    warehouse[name] = qty
m = int(input())
for s in range(m):
    name, qty = input().split()
    qty = int(qty)
    warehouse[name] += qty
for key, value in warehouse.items():
    print(f"{key}: {value}")




