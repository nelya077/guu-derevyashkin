"""
Задача 03-14. Сколько цифр в числе

Прочитайте целое число n (n ≥ 1) и выведите количество его цифр.

Считайте цифры циклом (// 10), без преобразования в строку.

Пример
------
Ввод:
12345
Вывод:
5
"""

# TODO: посчитайте количество цифр числа циклом

n = int(input())
total = 0
while n > 0:
    n % 10
    total += 1
    n = n // 10
print(total)