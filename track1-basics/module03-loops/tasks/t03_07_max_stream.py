"""
Задача 03-07. Максимум в потоке

Сначала поступает целое число n (n ≥ 1) — сколько чисел будет дальше.
Затем n целых чисел, каждое с отдельной строки. Выведите наибольшее из них.

Функцией max не пользоваться; список не создавать — обрабатывайте числа
по мере ввода.

Пример
------
Ввод:
5
3
9
1
7
5
Вывод:
9
"""

n = int(input())
max = int(input())
# TODO: прочитайте n чисел в цикле и найдите наибольшее
for i in range(n-1):
    n = int(input())
    if n > max:
        max = n
print(max)