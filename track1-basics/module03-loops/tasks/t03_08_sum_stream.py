"""
Задача 03-08. Сумма потока

Сначала поступает целое число n (n ≥ 1), затем n целых чисел — каждое
с отдельной строки. Выведите их сумму.

Функцией sum не пользоваться — накапливайте сумму в цикле.

Пример
------
Ввод:
4
1
2
3
4
Вывод:
10
"""

# TODO: прочитайте n, затем n чисел, и выведите их сумму
n = int(input())
total = 0
for i in range(1, n+1):
    num = int(input())
    total += num
print(total)