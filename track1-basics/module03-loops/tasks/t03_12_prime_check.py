"""
Задача 03-12. Простое число

Прочитайте целое число n (n ≥ 2) и выведите True, если оно простое
(делится только на 1 и на себя), иначе False.

Перебирайте делители от 2 до n − 1; как только найден делитель — число
не простое, и перебор можно прервать (break).

Пример
------
Ввод:
7
Вывод:
True
"""

# TODO: проверьте простоту числа перебором делителей
n = int(input())
number = True
for i in range(2, n):
    if n % i == 0:
        number = False
    break
print(number)